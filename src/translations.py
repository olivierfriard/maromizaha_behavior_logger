def language_codes() -> List[str]:
    return list(LANGUAGE_NAMES.keys())


def language_labels() -> List[str]:
    return [LANGUAGE_NAMES[code] for code in language_codes()]


def current_language() -> str:
    return _current_language


def language_label(code: str) -> str:
    return LANGUAGE_NAMES.get(code, LANGUAGE_NAMES[DEFAULT_LANGUAGE])


def language_from_label(label: str) -> str:
    for code, name in LANGUAGE_NAMES.items():
        if name == label:
            return code
    return DEFAULT_LANGUAGE


def set_language(code: str) -> None:
    global _current_language
    _current_language = code if code in LANGUAGE_NAMES else DEFAULT_LANGUAGE


def tr(text: str) -> str:
    if _current_language == DEFAULT_LANGUAGE:
        return text
    return TRANSLATIONS.get(_current_language, {}).get(text, text)


def trf(text: str, **kwargs: object) -> str:
    return tr(text).format(**kwargs)
